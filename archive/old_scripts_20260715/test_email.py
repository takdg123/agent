def main():
    """Run all email tests"""
    print("\n" + "="*70)
    print("🚀 TORRI EMAIL SYSTEM TEST")
    print("="*70)
    
    tests = [
        ("Email Configuration", test_email_config),
        ("yagmail Library", test_yagmail),
        ("Simple Test Email", send_test_email),
        ("Sample Report Email", test_full_report_email)
    ]
    
    results = []
    for name, test_func in tests:
        try:
            result = test_func()
            results.append((name, result))
        except KeyboardInterrupt:
            print("\n⚠️ Interrupted")
            break
        except Exception as e:
            print(f"\n❌ {name} failed: {e}")
            import traceback
            traceback.print_exc()
            results.append((name, False))
    
    # Summary
    print("\n" + "="*70)
    print("TEST SUMMARY")
    print("="*70)
    
    for name, result in results:
        status = "✅ PASS" if result else "❌ FAIL"
        print(f"{status}: {name}")
    
    passed = sum(1 for _, r in results if r)
    print(f"\nPassed: {passed}/{len(results)}")
    
    if passed >= 3:
        print("\n🎉 Email system is working!")
        print("\n📬 You should receive 2 test emails:")
        print("   1. Simple test email")
        print("   2. Sample report email")
    else:
        print("\n⚠️ Email system has issues. Check the errors above.")
    
    print("="*70 + "\n")
    
    return passed >= 3

if __name__ == "__main__":
    success = main()
    sys.exit(0 if success else 1)
