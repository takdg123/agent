#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Test Email Functionality
"""

import sys
from pathlib import Path
from datetime import datetime

sys.path.insert(0, str(Path(__file__).parent))

def test_email_config():
    """Test email configuration"""
    print("="*70)
    print("Testing Email Configuration")
    print("="*70 + "\n")
    
    from src.config import Config
    
    config = Config()
    
    print("📋 Email Configuration:")
    print("   Sender:", config.sender_email)
    print("   Recipient:", config.recipient_email)
    print("   Enabled:", config.email_enabled)
    pwd_display = '*' * len(config.sender_password) if config.sender_password else 'NOT SET'
    print("   Password:", pwd_display)
    
    if not config.email_enabled:
        print("\n❌ Email not enabled!")
        print("   Check SENDER_EMAIL, SENDER_PASSWORD, and RECIPIENT_EMAIL in .env")
        return False
    
    print("\n✅ Email configuration looks good!")
    return True

def test_yagmail():
    """Test yagmail import"""
    print("\n" + "="*70)
    print("Testing yagmail Library")
    print("="*70 + "\n")
    
    try:
        import yagmail
        print("✅ yagmail is installed")
        return True
    except ImportError:
        print("❌ yagmail not installed")
        print("   Installing: pip install yagmail")
        return False

def send_test_email():
    """Send a test email"""
    print("\n" + "="*70)
    print("Sending Test Email")
    print("="*70 + "\n")
    
    try:
        import yagmail
        from src.config import Config
        
        config = Config()
        
        if not config.email_enabled:
            print("❌ Email not configured")
            return False
        
        print(f"📧 Sending test email from {config.sender_email} to {config.recipient_email}...")
        
        # Create yagmail connection
        yag = yagmail.SMTP(user=config.sender_email, password=config.sender_password)
        
        # Email content
        subject = f"TORRI Test Email - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
        
        body = f"""
This is a test email from your TORRI research paper analysis system.

Test Details:
- Date/Time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
- System: {config.system_name}
- Sender: {config.sender_email}
- Recipient: {config.recipient_email}

If you're receiving this email, your email configuration is working correctly! ✅

---
TORRI Daily Research Report System
"""
        
        # Send email
        yag.send(
            to=config.recipient_email,
            subject=subject,
            contents=body
        )
        
        print(f"✅ Test email sent successfully!")
        print(f"\n📬 Check your inbox at: {config.recipient_email}")
        print(f"   Subject: {subject}")
        
        return True
        
    except Exception as e:
        print(f"❌ Failed to send email: {e}")
        print(f"\n💡 Common issues:")
        print(f"   1. Wrong email/password in .env")
        print(f"   2. Need Gmail App Password (not regular password)")
        print(f"   3. Gmail security settings blocking access")
        return False

