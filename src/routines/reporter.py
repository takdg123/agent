#!/usr/bin/env python3
"""
Report Routine for Agent System
Handles report generation and analysis
"""

from pathlib import Path
from typing import List, Dict, Any, Optional
from datetime import datetime

class ReportRoutine:
    """Handles report generation operations"""
    
    def __init__(self, config, db_manager, llm_analyzer, pdf_processor):
        self.config = config
        self.db_manager = db_manager
        self.llm_analyzer = llm_analyzer
        self.pdf_processor = pdf_processor
    
    def generate_daily_report(self, hours_back: int = 168) -> Dict[str, Any]:
        """Generate comprehensive daily report"""
        try:
            print("📊 Starting daily report generation...")
            
            # Get papers for analysis
            papers = self.db_manager.get_papers_with_content(hours_back)
            
            if not papers:
                print("ℹ️ No papers found for analysis")
                
                # Send "no new papers" email notification
                no_papers_content = self._format_no_papers_report()
                email_sent = self._send_email_report(no_papers_content, [], None)
                
                return {
                    "success": True,
                    "message": "No papers to analyze",
                    "papers_analyzed": 0,
                    "report_path": None,
                    "email_sent": email_sent
                }
            
            print(f"✅ Found {len(papers)} papers for analysis")
            
            # Generate individual paper summaries
            print("🧠 Generating individual paper summaries...")
            summaries = self._generate_paper_summaries(papers)
            
            # Format and save report
            print("📝 Formatting comprehensive report...")
            report_content = self._format_report(papers, summaries)
            
            # Save report
            report_path = self._save_report(report_content, papers)
            
            # Send email if configured
            email_sent = self._send_email_report(report_content, papers, report_path)
            
            return {
                "success": True,
                "message": "Daily report generated successfully",
                "papers_analyzed": len(papers),
                "summaries_generated": len(summaries),
                "report_path": report_path,
                "email_sent": email_sent
            }
            
        except Exception as e:
            print(f"❌ Daily report generation failed: {e}")
            return {"success": False, "error": str(e)}
    
    def _generate_paper_summaries(self, papers: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Generate individual paper summaries"""
        summaries = []
        
        for paper in papers:
            try:
                # Get enhanced PDF data
                enhanced_data = {}
                pdf_path = paper.get("pdf_path")
                if pdf_path and Path(pdf_path).exists():
                    enhanced_data = self.pdf_processor.process_pdf_for_analysis(pdf_path)
                
                # Generate summary
                summary = self.llm_analyzer.generate_paper_summary(paper, enhanced_data)
                if summary:
                    summaries.append({
                        "paper_id": paper.get("id", ""),
                        "title": paper.get("title", ""),
                        "summary": summary,
                        "enhanced_data": enhanced_data
                    })
                
            except Exception as e:
                print(f"⚠️ Error generating summary for {paper.get('title', 'Unknown')}: {e}")
        
        return summaries
    
    def _format_report(self, papers: List[Dict[str, Any]], summaries: List[Dict[str, Any]]) -> str:
        """Format the complete report"""
        now = datetime.now()
        
        report = f"""# {self.config.system_name} Daily Research Report
Generated: {now.strftime('%Y-%m-%d %H:%M:%S')}

## Summary
- Total Papers Analyzed: {len(papers)}
- Individual Summaries: {len(summaries)}

## Individual Paper Summaries
"""
        
        for summary in summaries:
            report += f"\n### {summary['title']}\n{summary['summary']}\n"
        
        return report
    
    def _format_no_papers_report(self) -> str:
        """Format a report when no new papers are found"""
        now = datetime.now()
        
        report = f"""# {self.config.system_name} Daily Research Report - No New Papers
Generated: {now.strftime('%Y-%m-%d %H:%M:%S')}

## Summary
- **Status**: No new papers found for analysis
- **Papers Analyzed**: 0
- **Reason**: No new papers matching your research criteria were published on arXiv today

---
This report was automatically generated by the {self.config.system_name} daily report system.
"""
        return report
    
    def _save_report(self, report_content: str, papers: List[Dict[str, Any]]) -> Optional[str]:
        """Save the report to file"""
        try:
            # Create reports directory
            reports_dir = self.config.reports_dir
            reports_dir.mkdir(parents=True, exist_ok=True)
            
            # Generate filename
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            system_name_lower = self.config.system_name.lower()
            filename = f"{system_name_lower}_report_{timestamp}.md"
            report_path = reports_dir / filename
            
            # Save report
            with open(report_path, 'w', encoding='utf-8') as f:
                f.write(report_content)
            
            print(f"📄 Report saved to: {report_path}")
            return str(report_path)
            
        except Exception as e:
            print(f"❌ Error saving report: {e}")
            return None
    
    def _send_email_report(self, report_content: str, papers: List[Dict[str, Any]], 
                          report_path: Optional[str] = None) -> bool:
        """Send email report via email"""
        try:
            # Check if email is enabled
            if not self.config.email_enabled:
                print("📧 Email not configured - skipping email sending")
                return False
            
            # Try to import yagmail
            try:
                import yagmail
            except ImportError:
                print("❌ yagmail not installed. Install with: pip install yagmail")
                print("📧 Email sending failed - missing dependency")
                return False
            
            # Get email configuration
            sender_email = self.config.sender_email
            sender_password = self.config.sender_password
            recipient_email = self.config.recipient_email
            
            # Create email body
            body = f"""Daily Research Report
Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
Papers analyzed: {len(papers)}

{report_content}

---
This report was automatically generated by the {self.config.system_name} daily report system.
"""
            
            # Send email using yagmail
            user = yagmail.SMTP(user=sender_email, password=sender_password)
            
            # Set appropriate subject based on whether there are papers
            if len(papers) == 0:
                subject = f"{self.config.system_name} Daily Report - No New Papers ({datetime.now().strftime('%Y-%m-%d')})"
            else:
                subject = f"{self.config.system_name} Daily Research Report - {datetime.now().strftime('%Y-%m-%d')}"
            
            user.send(
                to=recipient_email,
                subject=subject,
                contents=body
            )
            
            print(f"✅ Email sent successfully to {recipient_email}")
            return True
            
        except Exception as e:
            print(f"❌ Error sending email: {e}")
            return False
